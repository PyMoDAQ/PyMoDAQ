"""Builds the "legacy to current" page of the documentation from the deprecation warnings found in the source code.

Every call to ``deprecation_msg(...)`` or ``warnings.warn(..., DeprecationWarning)`` in ``packages/*/src`` is listed with
the place it is raised from and its message, so the page cannot drift from the code.

Regenerate the page with ``python docs/legacy_to_current.py`` (run from the root of the repository).
"""
import ast
from pathlib import Path
import re
import warnings

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / 'docs' / 'src' / 'developer_folder' / 'legacy_to_current.rst'

HEADER = """.. _legacy_to_current:

Legacy to current
=================

This page is generated from the deprecation warnings raised by the PyMoDAQ source code (``deprecation_msg`` calls and
``DeprecationWarning``). It lists what is still accepted but should not be used in new code, and what to use instead.
Models trained on older versions of PyMoDAQ, and old plugins, still use the names on the left: do not copy them.

Besides these entries, the word *preset* is obsolete: the Dashboard is used through the *experiment manager* and the
*state manager*. In the plugins, ``check_plugin`` reports most of the names below (see :ref:`instrument_plugin_doc`).

Do not edit this file by hand, run ``python docs/legacy_to_current.py`` after adding a deprecation.
"""


def _text(node) -> str:
    """Text of a string expression, with the computed parts replaced by ``...``"""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        return ''.join(_text(v) if isinstance(v, ast.Constant) else '...' for v in node.values)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return _text(node.left) + _text(node.right)
    return '...'


def _is_deprecation(call: ast.Call) -> bool:
    func = call.func
    if isinstance(func, ast.Name) and func.id == 'deprecation_msg':
        return True
    if isinstance(func, ast.Attribute) and func.attr == 'warn':
        return any('DeprecationWarning' in ast.dump(a) for a in call.args[1:2])
    return False


class _Visitor(ast.NodeVisitor):
    def __init__(self):
        self.scope: list[str] = []
        self.found: list[tuple[str, str]] = []

    def _scoped(self, node):
        self.scope.append(node.name)
        self.generic_visit(node)
        self.scope.pop()

    visit_ClassDef = visit_FunctionDef = visit_AsyncFunctionDef = _scoped

    def visit_Call(self, node):
        if _is_deprecation(node) and node.args:
            message = ' '.join(_text(node.args[0]).split())
            self.found.append(('.'.join(self.scope), message))
        self.generic_visit(node)


def collect() -> list[tuple[str, str, str]]:
    """(module, place in the module, message) for every deprecation found, sorted"""
    entries = set()
    for path in sorted(ROOT.glob('packages/*/src/**/*.py')):
        visitor = _Visitor()
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')  # invalid escape sequences of the scanned files
            visitor.visit(ast.parse(path.read_text(encoding='utf-8')))
        module = '.'.join(p for p in path.relative_to(path.parents[len(path.relative_to(ROOT).parts) - 4])
                          .with_suffix('').parts if p != '__init__')
        for scope, message in visitor.found:
            entries.add((module, scope, message))
    return sorted(entries)


def _escape(text: str) -> str:
    return re.sub(r'([\\*`|])', r'\\\1', text)


def page() -> str:
    out = [HEADER]
    module = None
    for mod, scope, message in collect():
        if mod != module:
            if module is not None:
                out.append('')
            out += [f'``{mod}``', '-' * (len(mod) + 4), '', '.. list-table::', '   :widths: 30 70', '']
            module = mod
        out += [f'   * - {"``" + scope + "``" if scope else "(on import)"}', f'     - {_escape(message)}']
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    PAGE.write_text(page(), encoding='utf-8')
    print(f'{PAGE} written')
